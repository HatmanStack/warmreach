#!/usr/bin/env node
/**
 * Copy the legal documents into the frontend bundle.
 *
 * `docs/legal/` is the single source of truth — it is what counsel reviews and
 * what `legal_acceptance_service.py` version-checks against. The acceptance
 * modal has to display that exact text, but Vite refuses to read files outside
 * the frontend root (and Vitest enforces its own allowlist on top), so the
 * documents are copied in rather than imported across the boundary.
 *
 * The copies are committed so the build needs no pre-step, and
 * `documents.sync.test.ts` fails if they drift from the source. Edit
 * `docs/legal/`, never the copies.
 */

import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const HERE = dirname(fileURLToPath(import.meta.url));
const SOURCE = join(HERE, '..', 'docs', 'legal');
const DEST = join(HERE, '..', 'frontend', 'src', 'features', 'legal', 'documents');

/**
 * The documents the acceptance modal can show.
 *
 * DATA_RETENTION.md is here even though it is not acknowledgment-gated: the
 * privacy policy's whole "How long we keep it" section points at it, so a
 * reader who cannot open it is reading a policy with a hole in it. README.md
 * stays out — it is the counsel-review checklist, internal working material
 * that has no business in a user-facing dialog.
 */
export const SYNCED_DOCUMENTS = [
  'ACCEPTABLE_USE.md',
  'DATA_RETENTION.md',
  'LINKEDIN_RISK_DISCLOSURE.md',
  'PRIVACY_POLICY.md',
  'TERMS_OF_USE.md',
];

const BANNER = '<!-- Generated by scripts/sync-legal-docs.mjs. Edit docs/legal/ instead. -->\n';

/**
 * Relative link targets on the lines a reader actually sees.
 *
 * `documents.ts` drops every `>` blockquote line before rendering — that block
 * is the internal DRAFT banner — and then strips relative link syntax down to
 * its text. So a link inside the banner never reaches a user and may point at
 * README.md; a link outside it becomes bare text, and if that text names a
 * document the bundle does not carry, the reader is told to consult something
 * they cannot open. That second case is what this rejects.
 */
function unresolvableLinks(body) {
  const found = [];
  for (const line of body.split('\n')) {
    if (line.trimStart().startsWith('>')) continue;
    for (const match of line.matchAll(/\[[^\]]+\]\(([^)]*)\)/g)) {
      const target = match[1].trim();
      if (/^(https?:|mailto:|#)/.test(target)) continue;
      if (!SYNCED_DOCUMENTS.includes(target.replace(/^\.\//, ''))) {
        found.push(target);
      }
    }
  }
  return found;
}

function main() {
  mkdirSync(DEST, { recursive: true });

  const missing = SYNCED_DOCUMENTS.filter((f) => !readdirSync(SOURCE).includes(f));
  if (missing.length) {
    console.error(`Missing source documents: ${missing.join(', ')}`);
    process.exit(1);
  }

  const bodies = new Map();
  const broken = [];
  for (const file of SYNCED_DOCUMENTS) {
    const body = readFileSync(join(SOURCE, file), 'utf8');
    bodies.set(file, body);
    for (const target of unresolvableLinks(body)) {
      broken.push(`${file} -> ${target}`);
    }
  }

  if (broken.length) {
    console.error('Documents link to something outside SYNCED_DOCUMENTS:');
    for (const entry of broken) console.error(`  ${entry}`);
    console.error(
      'The reader sees this link as bare text naming a document they cannot open.\n' +
        'Either add the target to SYNCED_DOCUMENTS or reword the sentence.'
    );
    process.exit(1);
  }

  // A copy left behind after an entry is removed from SYNCED_DOCUMENTS is worse
  // than a missing one: nothing checks it against docs/legal/ any more, so it
  // can drift silently while still being importable.
  const stale = readdirSync(DEST).filter((f) => f.endsWith('.md') && !SYNCED_DOCUMENTS.includes(f));
  if (stale.length) {
    console.error(`Stale copies in the bundle (not in SYNCED_DOCUMENTS): ${stale.join(', ')}`);
    process.exit(1);
  }

  for (const file of SYNCED_DOCUMENTS) {
    writeFileSync(join(DEST, file), BANNER + bodies.get(file));
    console.log(`synced ${file}`);
  }
}

main();
