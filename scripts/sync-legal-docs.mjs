#!/usr/bin/env node
/**
 * Copy the legal documents into the frontend bundle.
 *
 * `docs/legal/` is the single source of truth — it is what counsel reviews and
 * what `legal_acceptance_service.py` version-checks against. The acceptance
 * modal has to display that exact text, but Vite refuses to read files outside
 * the frontend root (and Vitest enforces its own allowlist on top), so the
 * documents are copied in rather than imported across the boundary.
 *
 * The copies are committed so the build needs no pre-step, and
 * `documents.sync.test.ts` fails if they drift from the source. Edit
 * `docs/legal/`, never the copies.
 */

import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const HERE = dirname(fileURLToPath(import.meta.url));
const SOURCE = join(HERE, '..', 'docs', 'legal');
const DEST = join(HERE, '..', 'frontend', 'src', 'features', 'legal', 'documents');

/** Only the documents the acceptance modal shows. README/retention are reference. */
export const SYNCED_DOCUMENTS = [
  'ACCEPTABLE_USE.md',
  'LINKEDIN_RISK_DISCLOSURE.md',
  'PRIVACY_POLICY.md',
  'TERMS_OF_USE.md',
];

const BANNER = '<!-- Generated by scripts/sync-legal-docs.mjs. Edit docs/legal/ instead. -->\n';

function main() {
  mkdirSync(DEST, { recursive: true });

  const missing = SYNCED_DOCUMENTS.filter((f) => !readdirSync(SOURCE).includes(f));
  if (missing.length) {
    console.error(`Missing source documents: ${missing.join(', ')}`);
    process.exit(1);
  }

  for (const file of SYNCED_DOCUMENTS) {
    const body = readFileSync(join(SOURCE, file), 'utf8');
    writeFileSync(join(DEST, file), BANNER + body);
    console.log(`synced ${file}`);
  }
}

main();
